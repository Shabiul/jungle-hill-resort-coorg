// Scans public/images and writes src/data/generated/image-manifest.ts
// (intrinsic size + tiny blur placeholder per image). Run: npm run images
const sharp = require("sharp");
const fs = require("fs");
const path = require("path");

const publicDir = path.join(process.cwd(), "public");
const out = path.join(process.cwd(), "src", "data", "generated", "image-manifest.ts");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

(async () => {
  const files = walk(path.join(publicDir, "images")).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
  const entries = {};
  for (const file of files) {
    const img = sharp(file).rotate();
    const meta = await img.metadata();
    const { width, height } = await sharp(await img.toBuffer()).metadata();
    const blur = await sharp(file).rotate().resize(12).blur().jpeg({ quality: 40 }).toBuffer();
    const key = "/" + path.relative(publicDir, file).split(path.sep).join("/");
    entries[key] = { width: width ?? meta.width, height: height ?? meta.height, blur: "data:image/jpeg;base64," + blur.toString("base64") };
  }
  const body =
    "// Generated by scripts/build-image-manifest.cjs. Do not edit.\n" +
    "export const imageManifest: Record<string, { width: number; height: number; blur: string }> = " +
    JSON.stringify(entries, null, 2) + ";\n";
  fs.writeFileSync(out, body);
  console.log(`${files.length} images written to ${path.relative(process.cwd(), out)}`);
})();
